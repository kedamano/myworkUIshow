function guessFields(name, trail) {
  const s = [...trail, name].join(" ");
  for (const [re, fields] of FIELD_RULES) {
    if (re.test(s)) return fields.filter((f) => allFields.includes(f)).slice(0, 4);
  }
  return ["工作经历.工作内容"];
}

function composeDesc(name, basis, values) {
  if (values.length === 1) {
    return `根据${basis}判断${name}，命中即登记为「${values[0]}」，未命中不打标。`;
  }
  return `根据${basis}判断${name}，取值分档为：${values.join("、")}。`;
}

let seq = 0;

function build(entry, trail) {
  const [name, second, values, customDesc] = entry;
  if (Array.isArray(second)) {
    return {
      id: "g" + ++seq,
      name,
      children: second.map((child) => build(child, [...trail, name])),
    };
  }
  const vals = String(values || "").split("；").map((v) => v.trim()).filter(Boolean);
  const mode = guessMode(name, trail);
  return {
    id: "L" + ++seq,
    name,
    tags: 0,
    tpl: {
      mode,
      tagMode: TAG_MODE[mode] || "规则打标",
      desc: customDesc || composeDesc(name, second, vals),
      fields: guessFields(name, trail),
      values: vals,
    },
  };
}

export const tree = RAW.map(([name, kids], i) => ({
  id: "k" + (i + 1),
  name,
  children: kids.map((k) => build(k, [name])),
}));

export function findLeaf(list, id) {
  for (const n of list) {
    if (n.id === id && !n.children) return n;
    if (n.children) {
      const hit = findLeaf(n.children, id);
      if (hit) return hit;
    }
  }
  return null;
}

export function allLeaves(list) {
  const out = [];
  const walk = (nodes, parents) => {
    nodes.forEach((n) => {
      if (n.children) walk(n.children, [...parents, n.name]);
      else out.push({ ...n, path: parents.join(" / ") });
    });
  };
  walk(list, []);
  return out;
}

const leafIdOf = (name) => {
  const hit = allLeaves(tree).find((l) => l.name === name);
  return hit ? hit.id : "k1";
};

